def main():
    text = FILE.read_text(encoding="utf-8")
    ok, skip, fail = [], [], []
    for label, old, new in EDITS:
        n = text.count(old)
        if n == 1:
            text = text.replace(old, new, 1)
            ok.append(label)
        elif n == 0:
            if new in text:
                skip.append(f"{label} (already applied)")
            else:
                fail.append(f"{label}: old NOT FOUND")
        else:
            fail.append(f"{label}: {n} matches (expected 1)")
    FILE.write_text(text, encoding="utf-8")
    print(f"[ok]   {len(ok):>2}: {', '.join(ok)}")
    if skip: print(f"[skip] {len(skip):>2}: {', '.join(skip)}")
    if fail: print(f"[FAIL] {len(fail):>2}: {', '.join(fail)}")


if __name__ == "__main__":
    main()
