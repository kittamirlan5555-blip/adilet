def apply(text: str) -> tuple[str, list[tuple[str, int]]]:
    log = []
    for old, new, label, replace_all in fixes:
        if replace_all:
            count = text.count(old)
            text = text.replace(old, new)
            log.append((label, count))
        else:
            count = text.count(old)
            if count == 0:
                log.append((f"NOT FOUND: {label}", 0))
            elif count > 1:
                log.append((f"AMBIG ({count}x): {label}", count))
            else:
                text = text.replace(old, new, 1)
                log.append((label, 1))
    return text, log


