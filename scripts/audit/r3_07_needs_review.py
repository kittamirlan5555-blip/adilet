def gates(slug, raws, origs):
    ok = True
    for suf, raw in raws.items():
        if "".join(re.sub(r"<[^>]+>", " ", raw).split()) != origs[suf]:
            print(f"!! INVARIANCE FAIL {slug}_{suf}")
            ok = False
        depth = bad = 0
        for t in re.finditer(r"<a\b[^>]*>|</a\s*>", raw, re.I):
            depth += 1 if t.group(0)[1] != "/" else -1
            if depth > 1 or depth < 0:
                bad += 1
        if bad or depth != 0:
            print(f"!! NESTED FAIL {slug}_{suf}")
            ok = False
    return ok


def fix_nalog_bank_z1():
    n_tot = 0
    raws, origs = {}, {}
    for suf in ("ready", "structured"):
        p = paths.FINAL / f"nalog_{suf}.html"
        raw = p.read_text(encoding="utf-8")
        origs[suf] = "".join(re.sub(r"<[^>]+>", " ", raw).split())
        raw, n = re.subn(
            r'(href="https?://[^"]*/docs/)Z950002444_#z1(")',
            r"\g<1>Z2600000258\g<2>", raw)
        raws[suf] = raw
        n_tot += n
    ok = gates("nalog", raws, origs)
    if APPLY and ok:
        for suf, raw in raws.items():
            (paths.FINAL / f"nalog_{suf}.html").write_text(raw, encoding="utf-8")
    return n_tot, ok


def fix_trudovoy_span():
    n_tot = 0
    raws, origs = {}, {}
    pat = re.compile(
        r'<a\b[^>]*href="https?://[^"]*/docs/Z070000252_#z0"[^>]*>(Закон)</a\s*>'
        r'([^<]{0,90}?"[^<"]{0,40}?)'
        r'<a\b[^>]*href="(https?://[^"]*/docs/Z070000252_)"[^>]*>'
        r'((?:(?!</a).)*?)</a\s*>"', re.S)
    for suf in ("ready", "structured"):
        p = paths.FINAL / f"trudovoy_{suf}.html"
        raw = p.read_text(encoding="utf-8")
        origs[suf] = "".join(re.sub(r"<[^>]+>", " ", raw).split())

        def repl(m):
            return (f'<a href="{m.group(3)}">{m.group(1)}{m.group(2)}'
                    f'{m.group(4)}"</a>')
        raw, n = pat.subn(repl, raw)
        raws[suf] = raw
        n_tot += n
    ok = gates("trudovoy", raws, origs)
    if APPLY and ok:
        for suf, raw in raws.items():
            (paths.FINAL / f"trudovoy_{suf}.html").write_text(raw, encoding="utf-8")
    return n_tot, ok


