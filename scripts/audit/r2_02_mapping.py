def main():
    apply_mode = "--apply" in sys.argv
    mp = al.CONFIG / "npa_mapping.json"
    m = json.loads(mp.read_text(encoding="utf-8"))

    L = ["# ANARA R2 — Фаза 2: пополнение npa_mapping.json", "",
         f"Режим: {'APPLY' if apply_mode else 'DRY-RUN'}.", "",
         "## Проверка существующих ключей", "",
         "| ключ | НГР ожид. | в маппинге | гейт |", "|---|---|---|---|"]
    ok = True
    for k, ngr in MUST_EXIST.items():
        got = m.get(k)
        g = "PASS" if got == ngr else "**FAIL**"
        ok &= got == ngr
        L.append(f"| «{k[:70]}…» | {ngr} | {got} | {g} |")

    L += ["", "## Новые ключи (верификация каждого НГР)", "",
          "| ключ | НГР | верификация | статус |", "|---|---|---|---|"]
    added, conflicts = [], []
    for k, (ngr, why) in ADD.items():
        if k in m and m[k] != ngr:
            conflicts.append((k, m[k], ngr))
            ok = False
            L.append(f"| «{k[:70]}…» | {ngr} | {why} | **КОНФЛИКТ: уже {m[k]}** |")
            continue
        st = "уже был" if k in m else "ДОБАВЛЕН"
        if k not in m:
            m[k] = ngr
            added.append(k)
        L.append(f"| «{k[:70]}…» | {ngr} | {why} | {st} |")

    L += ["", "## НЕ добавлено (по дизайну)", "",
          "- СТОП-класс (ждёт решения владельца): «законодательства РК об "
          "информатизации» (самоотсылка, ст.55/64-2), «законодательства РК "
          "в сфере обеспечения информационной безопасности» (ст.7-1 — "
          "подтверждённой внешней цели НЕТ).",
          "- Bare-quoted титулы перечня obrazovanie #3 («\"О некоммерческих "
          "организациях\"», «\"Об акционерных обществах\"») — как ключи "
          "словаря дают ложные матчи внутри названий законов-поправок; "
          "спаны Фазы 3 ставятся напрямую по флагу.",
          "- «с Предпринимательским кодексом РК» (флаги 1/17) — покрыто "
          "существующими ключами без предлога; третий перекрывающийся "
          "вариант в словарь не кладём.", "",
          f"**ИТОГ: добавлено {len(added)}, конфликтов {len(conflicts)}, "
          f"гейт существующих: {'PASS' if ok else 'FAIL'}**"]

    if apply_mode and ok:
        mp.write_text(json.dumps(m, ensure_ascii=False, indent=1),
                      encoding="utf-8")
        L.append("\n[APPLIED] npa_mapping.json записан")
    elif apply_mode:
        L.append("\n[ABORT] есть FAIL/конфликт — файл НЕ записан")

    out = R2 / "02_mapping_report.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    print(f"-> {out}")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
