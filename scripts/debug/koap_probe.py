    print(f"\n=== {rid}: ст.{art!r}, markers={markers} ===")
    if art is None:
        print("  [статья не указана в чеклисте]")
        continue
    div = soup.find("div", attrs={"data-type": "статья", "data-number": art})
    if not div:
        print(f"  [ст.{art} не найдена]")
        continue
    matches = []
    for p in div.find_all("p"):
        txt = p.get_text(" ", strip=True)
        if any(m in txt for m in markers):
            matches.append(p)
