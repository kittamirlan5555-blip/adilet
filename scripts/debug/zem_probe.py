for (rid, art, markers) in items:
    div = soup.find("div", attrs={"data-type": "статья", "data-number": art})
    print(f"\n=== {rid}: ст.{art} ===")
    if not div:
        print(f"  [ст. не найдена]")
        continue
    matches = []
    for p in div.find_all("p"):
        txt = p.get_text(" ", strip=True)
        if any(m in txt for m in markers):
            matches.append(p)
    if not matches:
        print(f"  [маркеры {markers!r} не найдены]")
        for p in div.find_all("p")[:5]:
            print(f"    z{p.get('id','?')}: {p.get_text(' ',strip=True)[:120]}")
        continue
    for p in matches[:3]:
        s = str(p)
        # компактный вывод
        s_short = re.sub(r'\s+', ' ', s)[:520]
        print(f"  z{p.get('id','?')}: {s_short}")
