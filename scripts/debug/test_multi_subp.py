import re

MULTI_SUBP_ARTICLE_PATTERN = re.compile(
    r'(подпункт(?:ах|ами|ом|у|а|е|ов)?)\s+'
    r'(\d+(?:-\d+)?)\)'
    r'((?:(?:\s*,\s*|\s*[–—-]\s*|\s+и\s+)\d+(?:-\d+)?\))*)'
    r'(?:\s+пункт(?:а|е|у|ом|ами)?\s+(\d+(?:-\d+)?))?'
    r'\s+стат(?:ь[яиейюёямих]+|ей)\s+(\d+(?:-\d+)?)',
    re.IGNORECASE
)

samples = [
    "Лицам с инвалидностью, указанным в подпунктах 1), 2) и 4) статьи 176 настоящего Кодекса, государственные",
    "Безработные, снятые с учета в соответствии с подпунктами 1) – 4) пункта 1 настоящей статьи, повторно",
    "указанным в подпунктах 1), 2) и 4) статьи 176 настоящего Кодекса",
]
for s in samples:
    print("Input:", s[:80])
    for m in MULTI_SUBP_ARTICLE_PATTERN.finditer(s):
        print(" MATCH:", m.group(0))
        print(" groups:", m.groups())
    print()
